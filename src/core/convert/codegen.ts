/**
 * Code snippet generators: cURL (bash), JavaScript fetch, Python requests, PowerShell.
 * Input is a request whose variables have (optionally) been resolved.
 */
import type { BodyConfig } from "../types";

export interface CodegenRequest {
  method: string;
  url: string;
  headers: [string, string][];
  body: BodyConfig;
}

export type CodegenLanguage = "curl" | "fetch" | "python" | "powershell";

export const CODEGEN_LANGUAGES: { id: CodegenLanguage; label: string; editor: "text" | "javascript" }[] = [
  { id: "curl", label: "cURL", editor: "text" },
  { id: "fetch", label: "JavaScript – fetch", editor: "javascript" },
  { id: "python", label: "Python – requests", editor: "text" },
  { id: "powershell", label: "PowerShell – Invoke-RestMethod", editor: "text" },
];

/** Headers the engine adds automatically; omitted from snippets for readability. */
const NOISE = new Set(["user-agent", "accept-encoding"]);

const shellQuote = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;
const jsString = (s: string) => JSON.stringify(s);
const pyString = (s: string) => JSON.stringify(s);
const psString = (s: string) => `'${s.replace(/'/g, "''")}'`;

function visibleHeaders(r: CodegenRequest): [string, string][] {
  return r.headers.filter(([k, v]) => {
    const l = k.toLowerCase();
    if (NOISE.has(l)) return false;
    if (l === "accept" && v === "*/*") return false;
    // Multipart boundaries are generated by each client library.
    if (l === "content-type" && r.body.mode === "formdata") return false;
    if (l === "content-length") return false;
    return true;
  });
}

function rawBody(b: BodyConfig): string | null {
  switch (b.mode) {
    case "raw":
      return b.raw;
    case "graphql": {
      let variables: unknown;
      try {
        variables = b.graphql.variables?.trim() ? JSON.parse(b.graphql.variables) : undefined;
      } catch {
        variables = b.graphql.variables;
      }
      return JSON.stringify({ query: b.graphql.query, ...(variables !== undefined ? { variables } : {}) });
    }
    case "urlencoded":
      return new URLSearchParams(
        b.urlencoded.filter((x) => x.enabled && x.key).map((x) => [x.key, x.value]),
      ).toString();
    default:
      return null;
  }
}

export function generateCurl(r: CodegenRequest): string {
  const lines = [
    `curl --location${r.method !== "GET" ? ` --request ${shellQuote(r.method)}` : ""} ${shellQuote(r.url)}`,
  ];
  for (const [k, v] of visibleHeaders(r)) lines.push(`--header ${shellQuote(`${k}: ${v}`)}`);
  const b = r.body;
  if (b.mode === "formdata") {
    for (const f of b.formdata.filter((x) => x.enabled && x.key)) {
      lines.push(
        f.type === "file"
          ? `--form ${shellQuote(`${f.key}=@"${f.fileName ?? "file"}"`)}`
          : `--form ${shellQuote(`${f.key}=${f.value}`)}`,
      );
    }
  } else if (b.mode === "urlencoded") {
    for (const x of b.urlencoded.filter((y) => y.enabled && y.key))
      lines.push(`--data-urlencode ${shellQuote(`${x.key}=${x.value}`)}`);
  } else if (b.mode === "binary" && b.binary) {
    lines.push(`--data-binary ${shellQuote(`@${b.binary.fileName}`)}`);
  } else {
    const raw = rawBody(b);
    if (raw) lines.push(`--data-raw ${shellQuote(raw)}`);
  }
  return lines.join(" \\\n  ");
}

export function generateFetch(r: CodegenRequest): string {
  const out: string[] = [];
  const headers = visibleHeaders(r);
  out.push("const headers = new Headers();");
  for (const [k, v] of headers) out.push(`headers.append(${jsString(k)}, ${jsString(v)});`);
  out.push("");
  const b = r.body;
  let bodyVar = "";
  if (b.mode === "formdata") {
    out.push("const body = new FormData();");
    for (const f of b.formdata.filter((x) => x.enabled && x.key)) {
      out.push(
        f.type === "file"
          ? `body.append(${jsString(f.key)}, fileInput.files[0], ${jsString(f.fileName ?? "file")});`
          : `body.append(${jsString(f.key)}, ${jsString(f.value)});`,
      );
    }
    bodyVar = "body";
  } else if (b.mode === "urlencoded") {
    out.push("const body = new URLSearchParams();");
    for (const x of b.urlencoded.filter((y) => y.enabled && y.key))
      out.push(`body.append(${jsString(x.key)}, ${jsString(x.value)});`);
    bodyVar = "body";
  } else if (b.mode === "binary" && b.binary) {
    out.push("const body = fileInput.files[0];");
    bodyVar = "body";
  } else {
    const raw = rawBody(b);
    if (raw) {
      if (b.mode === "raw" && b.language === "json") {
        try {
          out.push(`const body = JSON.stringify(${JSON.stringify(JSON.parse(raw), null, 2)});`);
        } catch {
          out.push(`const body = ${jsString(raw)};`);
        }
      } else out.push(`const body = ${jsString(raw)};`);
      bodyVar = "body";
    }
  }
  if (bodyVar) out.push("");
  out.push(`const response = await fetch(${jsString(r.url)}, {`);
  out.push(`  method: ${jsString(r.method)},`);
  out.push("  headers,");
  if (bodyVar) out.push("  body,");
  out.push('  redirect: "follow",');
  out.push("});");
  out.push("console.log(response.status, await response.text());");
  return out.join("\n");
}

export function generatePython(r: CodegenRequest): string {
  const out = ["import requests", "", `url = ${pyString(r.url)}`];
  const headers = visibleHeaders(r);
  out.push("headers = {");
  for (const [k, v] of headers) out.push(`    ${pyString(k)}: ${pyString(v)},`);
  out.push("}");
  const b = r.body;
  const args = ["url", "headers=headers"];
  if (b.mode === "formdata") {
    const text = b.formdata.filter((x) => x.enabled && x.key && x.type === "text");
    const files = b.formdata.filter((x) => x.enabled && x.key && x.type === "file");
    out.push("data = {");
    for (const f of text) out.push(`    ${pyString(f.key)}: ${pyString(f.value)},`);
    out.push("}");
    args.push("data=data");
    if (files.length) {
      out.push("files = [");
      for (const f of files)
        out.push(
          `    (${pyString(f.key)}, (${pyString(f.fileName ?? "file")}, open(${pyString(f.fileName ?? "file")}, "rb"))),`,
        );
      out.push("]");
      args.push("files=files");
    }
  } else if (b.mode === "urlencoded") {
    out.push("data = {");
    for (const x of b.urlencoded.filter((y) => y.enabled && y.key))
      out.push(`    ${pyString(x.key)}: ${pyString(x.value)},`);
    out.push("}");
    args.push("data=data");
  } else if (b.mode === "binary" && b.binary) {
    out.push(`data = open(${pyString(b.binary.fileName)}, "rb")`);
    args.push("data=data");
  } else {
    const raw = rawBody(b);
    if (raw) {
      out.push(`payload = ${pyString(raw)}`);
      args.push("data=payload");
    }
  }
  out.push(
    "",
    `response = requests.request(${pyString(r.method)}, ${args.join(", ")})`,
    "print(response.status_code)",
    "print(response.text)",
  );
  return out.join("\n");
}

export function generatePowerShell(r: CodegenRequest): string {
  const out: string[] = [];
  const headers = visibleHeaders(r).filter(([k]) => k.toLowerCase() !== "content-type");
  const contentType = r.headers.find(([k]) => k.toLowerCase() === "content-type")?.[1];
  out.push('$headers = New-Object "System.Collections.Generic.Dictionary[[String],[String]]"');
  for (const [k, v] of headers) out.push(`$headers.Add(${psString(k)}, ${psString(v)})`);
  out.push("");
  const b = r.body;
  const args = [`-Uri ${psString(r.url)}`, `-Method ${psString(r.method)}`, "-Headers $headers"];
  if (b.mode === "formdata") {
    out.push("$form = @{");
    for (const f of b.formdata.filter((x) => x.enabled && x.key)) {
      out.push(
        f.type === "file"
          ? `    ${psString(f.key)} = Get-Item -Path ${psString(f.fileName ?? "file")}`
          : `    ${psString(f.key)} = ${psString(f.value)}`,
      );
    }
    out.push("}");
    args.push("-Form $form");
  } else if (b.mode === "binary" && b.binary) {
    args.push(`-InFile ${psString(b.binary.fileName)}`);
  } else {
    const raw = rawBody(b);
    if (raw) {
      // Encode UTF-8 bytes so body text can never terminate a PowerShell literal.
      const base64 = btoa(
        Array.from(new TextEncoder().encode(raw), (byte) => String.fromCharCode(byte)).join(""),
      );
      out.push(`$body = [System.Convert]::FromBase64String('${base64}')`);
      args.push("-Body $body");
    }
  }
  const ct =
    b.mode === "graphql"
      ? "application/json"
      : b.mode === "urlencoded"
        ? "application/x-www-form-urlencoded"
        : contentType;
  if (ct && b.mode !== "formdata") args.push(`-ContentType ${psString(ct)}`);
  out.push(`$response = Invoke-RestMethod ${args.join(" ")}`);
  out.push("$response | ConvertTo-Json -Depth 10");
  return out.join("\n");
}

export function generateSnippet(lang: CodegenLanguage, r: CodegenRequest): string {
  switch (lang) {
    case "fetch":
      return generateFetch(r);
    case "python":
      return generatePython(r);
    case "powershell":
      return generatePowerShell(r);
    default:
      return generateCurl(r);
  }
}
