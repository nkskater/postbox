export const SDK_LIMITS = {
  sourceBytes: 2 * 1024 * 1024,
  operations: 500,
  typeNodes: 10000,
  typeDepth: 12,
  artifactBytes: 5 * 1024 * 1024,
};
export const sdkOptionsSchema = z.object({
  language: z.enum(["typescript", "python"]),
  name: z
    .string()
    .regex(/^[a-z][a-z0-9_]{0,49}$/)
    .refine(
      (name) => !RESERVED_PACKAGE_NAMES.has(name),
      "Choose a package name that does not shadow a runtime module or keyword",
    )
    .default("postbox_client"),
  version: z
    .string()
    .max(64)
    .regex(/^(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)(?:-[0-9A-Za-z]+(?:[.-][0-9A-Za-z]+)*)?$/)
    .refine(
      (value) =>
        value
          .split("-")[0]
          .split(".")
          .every((part) => Number(part) <= 2147483647),
      "Version components are too large",
    ),
});
export type SdkOptions = z.input<typeof sdkOptionsSchema>;
export type SdkType =
  | { kind: "json" | "string" | "number" | "boolean" | "null" }
  | { kind: "array"; items: SdkType }
  | { kind: "object"; properties: Record<string, SdkType>; required: string[] }
  | { kind: "union"; items: SdkType[] };
export interface SdkOperation {
  name: string;
  method: string;
  path: string;
  pathParameters: string[];
  query: Record<string, { type: SdkType; required: boolean }>;
  bodyMode: "none" | "json" | "text" | "urlencoded";
  bodyType: SdkType;
  responseType: SdkType;
  authRequired: boolean;
}
export interface SdkDefinition {
  operations: SdkOperation[];
  warnings: string[];
}
export interface SdkArtifact {
  filename: string;
  contentType: string;
  archive: Uint8Array;
  sha256: string;
  sourceHash: string;
  files: Record<string, string>;
  operations: string[];
}
